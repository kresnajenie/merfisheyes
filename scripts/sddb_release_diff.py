"""Compare two SpatialData-DB catalog releases before a sync.

    python scripts/sddb_release_diff.py <old-release-dir> <new-release-dir> [--out report.md]

Each dir holds the `catalog.parquet` of one `catalog-<date>` release of
theislab/spatialdata-db-client. Reports, as markdown: rows added / removed,
columns added / removed, how full every column is, the technologies,
organisms and buckets the sync has no convention for
(docs/specs/conventions.json), and rows already synced whose store URL or
title changed. Read-only; touches no database.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def load(d: Path) -> tuple[pd.DataFrame, dict]:
    import pyarrow.parquet as pq

    f = pq.ParquetFile(d / "catalog.parquet")
    meta = {k.decode(): v.decode()[:80] for k, v in (f.metadata.metadata or {}).items() if not k.startswith(b"ARROW")}
    return f.read().to_pandas(), meta


def main() -> None:
    old_dir, new_dir = Path(sys.argv[1]), Path(sys.argv[2])
    out = Path(sys.argv[sys.argv.index("--out") + 1]) if "--out" in sys.argv else None
    old, old_meta = load(old_dir)
    new, new_meta = load(new_dir)
    conv = json.loads((ROOT / "docs/specs/conventions.json").read_text())["catalog"]

    o_uids, n_uids = set(old.uid), set(new.uid)
    added, removed, kept = n_uids - o_uids, o_uids - n_uids, o_uids & n_uids
    L: list[str] = []
    p = L.append

    p(f"# SpatialData-DB release diff: {old_dir.name} → {new_dir.name}\n")
    p(f"Generated by `scripts/sddb_release_diff.py`. File metadata: old `{old_meta}`, new `{new_meta}`.\n")
    p("## Rows\n")
    p("| | count |\n|---|---:|")
    p(f"| old rows | {len(old)} |\n| new rows | {len(new)} |\n| added uids | {len(added)} |\n| removed uids | {len(removed)} |\n| kept uids | {len(kept)} |")
    p(f"| duplicate uids in new | {int(new.uid.duplicated().sum())} |\n")

    p("## Columns\n")
    p(f"- added: {', '.join(f'`{c}`' for c in sorted(set(new.columns) - set(old.columns))) or 'none'}")
    p(f"- removed: {', '.join(f'`{c}`' for c in sorted(set(old.columns) - set(new.columns))) or 'none'}\n")
    p("| column | dtype | filled (new) | filled (old) |\n|---|---|---:|---:|")
    for c in new.columns:
        nf = int(new[c].notna().sum())
        of = int(old[c].notna().sum()) if c in old else None
        p(f"| `{c}` | {new[c].dtype} | {nf} / {len(new)} | {'—' if of is None else f'{of} / {len(old)}'} |")
    p("")

    p("## Values the sync has no convention for (`docs/specs/conventions.json`)\n")
    tech = new.technology.value_counts()
    p("| technology | rows | display name |\n|---|---:|---|")
    for t, n in tech.items():
        p(f"| {t} | {n} | {conv['platforms'].get(t, '**none — shown raw**')} |")
    p("")
    orgs = new.organism.dropna().str.lower().value_counts()
    missing_orgs = {o: n for o, n in orgs.items() if o not in conv["species"]}
    p(f"- organisms without a display name (capitalised raw): {missing_orgs or 'none'}")
    buckets = new.zarr_url.str.extract(r"^s3://([^/]+)/")[0].value_counts()
    p(f"- buckets: {buckets.to_dict()}; without a known region: "
      f"{[b for b in buckets.index if b not in conv['bucketRegions']] or 'none'}")
    bad = new[~new.zarr_url.str.match(r"^s3://[^/]+/.+")]
    p(f"- rows whose `zarr_url` is not `s3://bucket/key`: {len(bad)}\n")

    p("## Kept uids whose fields changed\n")
    k = old.set_index("uid").loc[sorted(kept)]
    n = new.set_index("uid").loc[sorted(kept)]
    p("| column | rows changed |\n|---|---:|")
    for c in [c for c in old.columns if c in new.columns and c != "uid"]:
        a, b = k[c].astype(str), n[c].astype(str)
        ch = int((a != b).sum())
        if ch:
            p(f"| `{c}` | {ch} |")
    moved = (k.zarr_url != n.zarr_url)
    p(f"\nStore URL moved for {int(moved.sum())} kept uids" + (f", e.g. `{k.zarr_url[moved].iloc[0]}` → `{n.zarr_url[moved].iloc[0]}`" if moved.any() else "") + ".\n")

    p("## Removed uids\n")
    r = old[old.uid.isin(removed)]
    p(f"By technology: {r.technology.value_counts().to_dict()}.")
    p(f"Same `canonical_key` present in the new release under another uid: "
      f"{int(r.canonical_key.isin(set(new.canonical_key.dropna())).sum())} of {len(r)}.\n")

    p("## Added uids\n")
    a = new[new.uid.isin(added)]
    p(f"By technology: {a.technology.value_counts().to_dict()}.\n")
    p(f"Size: {a.size_bytes.sum() / 1e12:.1f} TB in total, median {a.size_bytes.median() / 1e9:.2f} GB.\n")

    text = "\n".join(L)
    if out:
        out.write_text(text)
        print("wrote", out)
    else:
        print(text)


if __name__ == "__main__":
    main()
